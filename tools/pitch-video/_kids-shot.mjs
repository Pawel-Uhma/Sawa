import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: "pl-PL" });
const p = await ctx.newPage();
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
await p.goto("http://localhost:3017/", { waitUntil: "networkidle" });
await p.getByText("Znam Sawę, przejdź do pytań").click();
await p.getByText("Trochę znam").click();
await p.getByText("Historia", { exact: true }).click();
await p.getByRole("button", { name: "Dalej" }).click();
await p.getByText("Krótko i z humorem").click();
await p.getByText("Kto będzie słuchał?").first().waitFor();
await p.waitForTimeout(700);
await p.screenshot({ path: `${out}/1-onboarding.png` });
await p.getByText("Jadę z dzieckiem").click();
await p.waitForTimeout(2500);
console.log("profile", await p.evaluate(() => localStorage.getItem("sawa.profile.v1")));
await p.screenshot({ path: `${out}/2-after.png` });
const menu = p.getByRole("button", { name: /menu|Sawa/i }).first();
await menu.click().catch((e) => console.log("menu?", e.message));
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/3-menu.png` });
await p.getByText("Kto słucha").first().click().catch((e) => console.log("row?", e.message));
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/4-modal.png` });
console.log("errors", errors);
await b.close();
